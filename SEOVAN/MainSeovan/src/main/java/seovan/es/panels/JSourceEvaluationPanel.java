                jEvalPubPubQuality.setText(QualityOfPublications);

                NodeList NLOB = tmpXMLDI.GetChilDNodeRecursed(NLEV, "Objectivity");
                String ClarityAndAccuracy = tmpXMLDI.GetResultFromRecurseDeeperNode(NLOB, "ClarityAndAccuracy");
                String NonCommercial = tmpXMLDI.GetResultFromRecurseDeeperNode(NLOB, "NonCommercial");
