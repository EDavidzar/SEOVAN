    int GetIndexFromComboStringList(JComboBox<String> JCB, String sToSearch) {
        int theindex = -1;
        int isize = JCB.getItemCount();
        for (int i = 0; i < isize; i++) {
            String sitem = JCB.getItemAt(i);
            if (sitem.toLowerCase() == null ? sToSearch.toLowerCase() == null : sitem.toLowerCase().equals(sToSearch.toLowerCase())) {
                theindex = i;
                break;
            }
        }
        return theindex;
    }

