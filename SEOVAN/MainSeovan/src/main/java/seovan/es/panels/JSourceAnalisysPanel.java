        String sElement = String.valueOf(itmpIndexItemSource);
        DBMSAP.SelectManyResults("desidaniespsources.elements_record", "idelements_record", sElement, InParameters, OutParameters);
        elements_autorithies = OutParameters.get(0);
        elements_contents = OutParameters.get(1);
        elements_evaluation = OutParameters.get(2);
        elements_identification = OutParameters.get(3);
        elements_sourceapp = OutParameters.get(4);
